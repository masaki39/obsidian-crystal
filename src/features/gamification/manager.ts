import { getWeeklyXPSeries, pruneDailyXPLog, sumRecentXP } from './rules/xp-log';
import { GAMIFICATION_FLASH_EVENT, type GamificationSnapshot, type TodayProgress, VIEW_TYPE_GAMIFICATION } from './types';
const moment = require('moment');

// Gamification: reward completing daily-note tasks (e.g. those generated by the
// Silhouette plugin) with XP, levels and streaks, using variable rewards so the
// payoff isn't predictable. See docs for the psychology behind this design:
// dopamine peaks at *anticipation*, not at the reward itself, and unpredictable
// (variable-ratio) rewards sustain engagement far better than fixed ones.

interface StreakUpdateResult {
    newlyUnlocked: Badge[];
    newBestStreak: boolean;
    isComeback: boolean;
    freezeMilestoneBonus: number;
}

type PluginWithSettings = Plugin & { settings: CrystalPluginSettings; saveSettings(): Promise<void> };

export class GamificationManager {
    private app: App;
    private plugin: PluginWithSettings;
    private settings: CrystalPluginSettings;
    private random: () => number;
    private taskCounts: Map<string, number> = new Map();
    private taskTotals: Map<string, number> = new Map();
    private todayProgress: TodayProgress | null = null;
    private statusBarItem: HTMLElement | null = null;
    private flashTimeoutId: number | null = null;
    private saveDebounceId: number | null = null;
    private onStatusBarClick?: () => void;
    /** Path Better Word Count writes its stats to (its own default; not configurable here). */
    private vaultStatsPath = '';
    /** Last successfully parsed read of that file, cached in memory; null when unavailable. */
    private lastVaultStats: VaultStatsFile | null = null;
    private charStatsAvailable = false;
    private charStatsDebounceId: number | null = null;
    /** Reentrancy guard for `refreshWordStats`: it's invoked from three
     * uncoordinated entry points (`onLoad`, `updateSettings`, and the
     * debounced file-watch handler) and awaits a file read, so without this
     * two overlapping calls could both read the same pre-mutation state and
     * double-grant XP for the same milestone/goal crossing. */
    private refreshingWordStats = false;

    constructor(
        app: App,
        plugin: PluginWithSettings,
        settings: CrystalPluginSettings,
        random: () => number = Math.random,
        onStatusBarClick?: () => void
    ) {
        this.app = app;
        this.plugin = plugin;
        this.settings = settings;
        this.random = random;
        this.onStatusBarClick = onStatusBarClick;
    }

    updateSettings(settings: CrystalPluginSettings) {
        this.settings = settings;
        this.renderStatusBar();
        // e.g. the settings tab's "Reset progress" button changes the
        // underlying data — make sure an already-open sidebar reflects it.
        this.refreshViews();
        // Re-check the writing goal in case gamification/the goal was just
        // turned on and today's characters already clear it.
        if (this.vaultStatsPath) {
            this.refreshWordStats().catch((error) => {
                console.error('Crystal gamification: failed to refresh word-count stats', error);
            });
        }
    }

    onLoad() {
        this.statusBarItem = this.plugin.addStatusBarItem();
        this.statusBarItem.addClass('crystal-gamification-status');
        if (this.onStatusBarClick) {
            this.statusBarItem.addClass('mod-clickable');
            this.plugin.registerDomEvent(this.statusBarItem, 'click', () => this.onStatusBarClick?.());
        }
        this.renderStatusBar();

        this.plugin.registerEvent(
            this.app.vault.on('modify', (file) => {
                if (file instanceof TFile) {
                    this.handleFileModify(file).catch((error) => {
                        console.error('Crystal gamification: failed to process file modification', error);
                    });
                }
            })
        );

        this.plugin.registerEvent(
            this.app.workspace.on('file-open', (file) => {
                if (file instanceof TFile) {
                    this.cacheBaseline(file).catch((error) => {
                        console.error('Crystal gamification: failed to cache baseline', error);
                    });
                }
            })
        );

        this.cacheTodayBaseline();

        // Optional Better Word Count integration: it writes its stats file
        // directly via the adapter (not through the normal Vault file API),
        // so `vault.on('modify')` never fires for it — 'raw' is Obsidian's
        // undocumented-but-real event for exactly this case (also used by
        // e.g. the Hot Reload community plugin to watch `.obsidian/plugins`).
        this.vaultStatsPath = defaultVaultStatsPath(this.app);
        this.refreshWordStats().catch((error) => {
            console.error('Crystal gamification: failed to read word-count stats', error);
        });
        this.plugin.registerEvent(
            (this.app.vault as any).on('raw', (path: string) => {
                if (path !== this.vaultStatsPath) return;
                this.debouncedRefreshWordStats();
            })
        );
    }

    private isDailyNote(file: TFile): boolean {
        return getDateFromFile(file, 'day') !== null;
    }

    /**
     * Record `xp` earned on `dateStr` into the daily XP log — the source for
     * the sidebar's weekly/monthly chart and the best-week personal record —
     * pruning old entries against the real "today" so the log doesn't grow
     * forever. Shared by every XP-earning path (task completion, hitting the
     * daily writing goal, and mid-goal milestone bonuses) so none of them can
     * silently under-report into those views by forgetting this step.
     */
    private logDailyXP(dateStr: string, todayStr: string, xp: number) {
        if (xp <= 0) return;
        this.settings.gamificationDailyXPLog[dateStr] = (this.settings.gamificationDailyXPLog[dateStr] ?? 0) + xp;
        this.settings.gamificationDailyXPLog = pruneDailyXPLog(this.settings.gamificationDailyXPLog, todayStr);
    }

    /**
     * Record a file's current completed-task count without granting any reward.
     * Used so we never retroactively reward tasks that were already checked
     * before the plugin observed the file.
     */
    private async cacheBaseline(file: TFile) {
        if (!this.isDailyNote(file)) return;
        if (this.taskCounts.has(file.path)) return;
        const content = await this.app.vault.cachedRead(file);
        // Re-check after the await: handleFileModify may have raced ahead and
        // already established a (more current) baseline for this file while
        // we were reading it. Don't clobber it with a possibly-stale read.
        if (this.taskCounts.has(file.path)) return;
        this.taskCounts.set(file.path, countCompletedTasks(content));
        this.taskTotals.set(file.path, countTotalTasks(content));
        this.refreshTodayProgress(file, content);
    }

    /** Update the cached today-progress snapshot if `file` is today's daily note. */
    private refreshTodayProgress(file: TFile, content: string) {
        const date = getDateFromFile(file, 'day');
        if (!date || date.format('YYYY-MM-DD') !== moment().format('YYYY-MM-DD')) return;
        this.todayProgress = { completed: countCompletedTasks(content), total: countTotalTasks(content) };
    }

    private cacheTodayBaseline() {
        try {
            const allNotes = getAllDailyNotes();
            const today = getDailyNote(moment(), allNotes);
            if (today) {
                this.cacheBaseline(today).catch((error) => {
                    console.error('Crystal gamification: failed to cache today baseline', error);
                });
            }
        } catch (error) {
            // Daily notes folder/settings not available yet; nothing to prime.
        }
    }

    private async handleFileModify(file: TFile) {
        if (!this.settings.gamificationEnabled || !this.isDailyNote(file)) return;

        const date = getDateFromFile(file, 'day');
        const content = await this.app.vault.cachedRead(file);

        const newCount = countCompletedTasks(content);
        const newTotal = countTotalTasks(content);
        const prevCount = this.taskCounts.get(file.path);
        const prevTotal = this.taskTotals.get(file.path);
        this.taskCounts.set(file.path, newCount);
        this.taskTotals.set(file.path, newTotal);

        // First time we see this file: only establish the baseline, still refresh the view.
        if (prevCount === undefined || !date) {
            this.refreshTodayProgress(file, content);
            this.refreshViews();
            return;
        }

        const delta = newCount - prevCount;
        if (delta <= 0) {
            // No new completion (e.g. a task was unchecked, or a non-task edit).
            // Only touch the view if something task-related actually changed —
            // an unrelated prose edit shouldn't tear down and rebuild the whole
            // panel (that was destroying badge tooltips mid-hover).
            if (newCount !== prevCount || newTotal !== prevTotal) {
                this.refreshTodayProgress(file, content);
                this.refreshViews();
            }
            return;
        }

        this.refreshTodayProgress(file, content);

        const dateStr = date.format('YYYY-MM-DD');
        // The real "today", independent of which day's note was edited — used
        // for anything that must stay anchored to the actual calendar (log
        // pruning, freeze-token refill), so backfilling an old note can never
        // wipe out or misdate today's own data. `dateStr` (the note's date)
        // still attributes XP/tasks/streak to the day the work was for.
        const todayStr = moment().format('YYYY-MM-DD');

        const levelBefore = calculateLevel(this.settings.gamificationTotalXP).level;

        let gainedXP = 0;
        let bestTier: RewardTier = 'normal';
        for (let i = 0; i < delta; i++) {
            const reward = rollReward(this.random);
            this.settings.gamificationTotalXP += reward.xp;
            gainedXP += reward.xp;
            if (tierRank(reward.tier) > tierRank(bestTier)) bestTier = reward.tier;
        }
        const levelAfter = calculateLevel(this.settings.gamificationTotalXP).level;
        const leveledUp = levelAfter > levelBefore;

        this.settings.gamificationTotalTasksCompleted += delta;
        if (!this.settings.gamificationStartDate) this.settings.gamificationStartDate = dateStr;
        this.logDailyXP(dateStr, todayStr, gainedXP);

        this.settings.gamificationDailyTaskLog[dateStr] = (this.settings.gamificationDailyTaskLog[dateStr] ?? 0) + delta;
        this.settings.gamificationDailyTaskLog = pruneDailyXPLog(this.settings.gamificationDailyTaskLog, todayStr);
        const todayTaskCount = this.settings.gamificationDailyTaskLog[dateStr];
        const newBestDayTasks = todayTaskCount > this.settings.gamificationBestDayTasks;
        if (newBestDayTasks) this.settings.gamificationBestDayTasks = todayTaskCount;

        const weekXP = sumRecentXP(this.settings.gamificationDailyXPLog, dateStr, 7);
        const newBestWeekXP = weekXP > this.settings.gamificationBestWeekXP;
        if (newBestWeekXP) this.settings.gamificationBestWeekXP = weekXP;

        const { newlyUnlocked, newBestStreak, isComeback, freezeMilestoneBonus } = this.updateStreakAndBadges(dateStr, todayStr);

        const specialUnlocks = checkNewlySpecialUnlocks(
            { hour: new Date().getHours(), todayTaskCount },
            this.settings.gamificationUnlockedBadges
        );
        if (specialUnlocks.length > 0) {
            this.settings.gamificationUnlockedBadges.push(...specialUnlocks.map((b) => b.id));
        }
        const allNewBadges = [...newlyUnlocked, ...specialUnlocks];

        // One status-bar moment per completion — pick the most exciting thing that happened.
        this.flashMostExciting(
            [
                { condition: allNewBadges.length > 0, flash: () => this.flashBadge(allNewBadges[allNewBadges.length - 1]) },
                { condition: leveledUp, flash: () => this.flashLevelUp(levelAfter) },
                { condition: freezeMilestoneBonus > 0, flash: () => this.flash([{ icon: 'snowflake', text: `+${freezeMilestoneBonus} FREEZE` }], 2500) },
                { condition: newBestStreak || newBestDayTasks || newBestWeekXP, flash: () => this.flashPersonalBest({ streak: newBestStreak, dayTasks: newBestDayTasks, weekXP: newBestWeekXP }) },
                { condition: isComeback, flash: () => this.flash([{ icon: 'leaf', text: `Best ${this.settings.gamificationBestStreak}d kept · fresh start` }], 2500) },
            ],
            () => this.flashReward({ xp: gainedXP, tier: bestTier })
        );
        this.refreshViews();
        // Debounced rather than awaited: checking off several tasks in a row
        // should coalesce into a single data.json write (and a single
        // updateSettings() cascade across every other service) instead of one
        // per checkbox. flushPendingSave() forces it out on unload.
        this.debouncedSave();
    }

    /**
     * Advance the streak (bridging a missed day with a freeze token if one is
     * available), refill freeze tokens on a new calendar month, grant
     * milestone freeze bonuses, track the best-ever streak, and unlock any
     * newly-earned badges.
     *
     * `activeDate` is the day the completed task belongs to (the daily
     * note's date); `today` is the real current date. Freeze-token refill
     * always uses `today`, since "this calendar month" is a real-time concept
     * that shouldn't shift just because an old note was edited.
     *
     * If `activeDate` is *earlier* than the last recorded active date, this
     * is a backfill (catching up on a stale, already-past daily note) rather
     * than today's activity — the streak, freeze tokens and last-active date
     * are left untouched so backfilling never resets progress that's already
     * been earned. XP/badges from the completion still apply regardless.
     */
    private updateStreakAndBadges(activeDate: string, today: string): StreakUpdateResult {
        const advance = resolveStreakAdvance({
            activeDate,
            today,
            previousActiveDate: this.settings.gamificationLastActiveDate || null,
            currentStreak: this.settings.gamificationStreak,
            freezeTokensAvailable: this.settings.gamificationFreezeTokensAvailable,
            freezeTokensRefillMonth: this.settings.gamificationFreezeTokensRefillMonth,
            bestStreak: this.settings.gamificationBestStreak,
            freezeMilestonesGranted: this.settings.gamificationFreezeMilestonesGranted,
            restDayOfWeek: this.settings.gamificationRestDayOfWeek,
        });

        this.settings.gamificationFreezeTokensAvailable = advance.freezeTokensAvailable;
        this.settings.gamificationFreezeTokensRefillMonth = advance.freezeTokensRefillMonth;
        this.settings.gamificationStreak = advance.streak;
        this.settings.gamificationLastActiveDate = advance.lastActiveDate;
        this.settings.gamificationBestStreak = advance.bestStreak;

        if (advance.freezeTokensUsed > 0) {
            this.settings.gamificationFreezeTokenLog.push(activeDate);
            this.settings.gamificationFreezeTokenLog = this.settings.gamificationFreezeTokenLog.slice(-10);
        }
        if (advance.newMilestones.length > 0) {
            this.settings.gamificationFreezeMilestonesGranted.push(...advance.newMilestones);
        }

        return {
            newlyUnlocked: this.applyNewBadgeUnlocks(),
            newBestStreak: advance.newBestStreak,
            isComeback: advance.isComeback,
            freezeMilestoneBonus: advance.newMilestones.length,
        };
    }

    /**
     * Check every level/streak/lifetime-chars badge threshold against current
     * settings and unlock any newly-met one. Split out of
     * `updateStreakAndBadges` (which also advances the streak — an "active
     * day" concept) so a badge threshold crossed by XP alone, with no
     * corresponding streak advancement — e.g. a mid-goal writing milestone
     * bonus, which shouldn't extend the streak by itself — still gets
     * checked instead of silently staying locked until some later event
     * happens to re-check it.
     */
    private applyNewBadgeUnlocks(): Badge[] {
        const lifetimeChars = this.lastVaultStats ? lifetimeCharactersWritten(this.lastVaultStats) : 0;
        // Self-heal if the external stats file's lifetime total ever drops
        // below the baseline (e.g. Better Word Count's stats file was
        // deleted or rebuilt after the baseline was captured) — otherwise
        // `charsBadgeEligible` would floor at 0 forever with no way to
        // recover chars badges short of a full progress reset, even though
        // the user is still actively writing.
        //
        // Gate this on an actual successful read (`this.lastVaultStats` set)
        // rather than just "baseline > lifetimeChars": before the first
        // successful read (e.g. right after `onload`, or after a transient
        // parse failure while Better Word Count is mid-write), lifetimeChars
        // defaults to 0, which is always below any real baseline — clamping
        // on that would wrongly zero out a just-captured reset baseline and
        // cause every chars badge to instantly re-unlock on the next
        // successful read, exactly the "clean slate" a reset just promised.
        if (this.lastVaultStats && this.settings.gamificationCharsBadgeBaseline > lifetimeChars) {
            this.settings.gamificationCharsBadgeBaseline = lifetimeChars;
        }
        const state = {
            level: calculateLevel(this.settings.gamificationTotalXP).level,
            streak: this.settings.gamificationStreak,
            totalXP: this.settings.gamificationTotalXP,
            chars: charsBadgeEligible(lifetimeChars, this.settings.gamificationCharsBadgeBaseline),
        };
        const newlyUnlocked = checkNewlyUnlockedBadges(state, this.settings.gamificationUnlockedBadges);
        if (newlyUnlocked.length > 0) {
            this.settings.gamificationUnlockedBadges.push(...newlyUnlocked.map((b) => b.id));
        }
        return newlyUnlocked;
    }

    /**
     * Debounce re-reads of the stats file: Better Word Count writes it on
     * every keystroke (its own 50ms debounce), so without this we'd re-parse
     * the whole JSON file constantly while the user types.
     */
    private debouncedRefreshWordStats() {
        if (this.charStatsDebounceId !== null) {
            window.clearTimeout(this.charStatsDebounceId);
        }
        this.charStatsDebounceId = window.setTimeout(() => {
            this.charStatsDebounceId = null;
            this.refreshWordStats().catch((error) => {
                console.error('Crystal gamification: failed to refresh word-count stats', error);
            });
        }, 400);
        this.plugin.registerInterval(this.charStatsDebounceId);
    }

    /**
     * Re-read the Better Word Count stats file and update the cached snapshot
     * of it. Guarded against reentrancy: this is invoked from three
     * uncoordinated entry points (`onLoad`, `updateSettings`, and the
     * debounced file-watch handler), and its body awaits a file read before
     * mutating XP/milestone state — without this guard, two overlapping
     * calls could both read the same pre-mutation state and double-grant XP
     * for the same milestone/goal crossing. A skipped overlap just means the
     * next natural trigger (another keystroke, another settings change) picks
     * up the latest state instead — nothing is lost, just briefly deferred.
     */
    private async refreshWordStats() {
        if (this.refreshingWordStats) return;
        this.refreshingWordStats = true;
        try {
            await this.doRefreshWordStats();
        } finally {
            this.refreshingWordStats = false;
        }
    }

    /**
     * Better Word Count writes its stats file on essentially every keystroke
     * (its own 50ms debounce, plus our own 400ms one on top), so most calls
     * here are routine "still writing" ticks with nothing new to report —
     * those only patch the live writing-progress bar in place
     * (`updateTodayCharsLive`) rather than triggering a full sidebar rebuild.
     * A full `refreshViews()` is reserved for actual state changes: crossing
     * a mid-goal milestone, or hitting the daily goal itself (which grants
     * the same kind of variable reward a task completion would, and extends
     * the *same* streak tasks use — an active day is "completed a task OR hit
     * the writing goal").
     */
    private async doRefreshWordStats() {
        const stats = await readVaultStats(this.app, this.vaultStatsPath);
        const wasAvailable = this.charStatsAvailable;
        this.lastVaultStats = stats;
        this.charStatsAvailable = stats !== null;

        if (!stats || !this.settings.gamificationEnabled) {
            if (wasAvailable !== this.charStatsAvailable) this.refreshViews();
            return;
        }

        const todayStr = moment().format('YYYY-MM-DD');
        const goal = this.settings.gamificationDailyCharGoal;
        const charsToday = charactersOn(stats, todayStr);

        if (this.settings.gamificationCharMilestonesDate !== todayStr) {
            this.settings.gamificationCharMilestonesDate = todayStr;
            this.settings.gamificationCharMilestonesReached = [];
        }

        // Grant any newly-crossed mid-goal milestone bonus first (silently
        // folding its XP in), but don't return early — a big single update
        // (e.g. pasting a large block of text) can cross a milestone *and*
        // the daily goal in the very same stats read, and the goal
        // completion (streak extension, level/badge checks) must still fire
        // in that same call rather than waiting for another edit that may
        // never come today. See `resolveWordStatsTick`.
        const { newMilestones, goalReached } = resolveWordStatsTick({
            charsToday,
            goal,
            milestonesReached: this.settings.gamificationCharMilestonesReached,
            goalAlreadyAchievedToday: this.settings.gamificationCharGoalLastAchievedDate === todayStr,
        });

        // Snapshot the level *before* folding in the milestone bonus XP below,
        // so that if the goal is also reached this same tick, grantCharGoalReward
        // can compare against the level as it stood before either reward —
        // otherwise a level-up caused by the milestone bonus alone would
        // already be reflected in its own "before" snapshot and go unnoticed
        // (no LEVEL UP flash) even though the user's level silently changed.
        // Only worth computing when there's actually a reward to check against —
        // this function runs on essentially every keystroke (see doc comment
        // above), and the routine "still writing, nothing crossed" case is by
        // far the most common tick.
        const levelBeforeTick = (newMilestones.length > 0 || goalReached)
            ? calculateLevel(this.settings.gamificationTotalXP).level
            : 0;

        let milestoneBonus = 0;
        if (newMilestones.length > 0) {
            this.settings.gamificationCharMilestonesReached.push(...newMilestones);
            milestoneBonus = newMilestones.reduce((sum) => sum + rollCharMilestoneBonus(this.random), 0);
            if (milestoneBonus > 0) {
                this.settings.gamificationTotalXP += milestoneBonus;
                this.logDailyXP(todayStr, todayStr, milestoneBonus);
            }
        }

        if (goalReached) {
            this.grantCharGoalReward(todayStr, levelBeforeTick);
            return;
        }

        if (newMilestones.length > 0) {
            // Badge/level/best-week checks run regardless of whether the
            // milestone's own small XP bonus happened to roll (see
            // `rollCharMilestoneBonus`'s 40% chance) — the milestone crossing
            // itself reflects real writing progress (lifetime characters,
            // which chars-badges are keyed on) independent of that coin flip,
            // so gating these checks behind "bonus > 0" would leave a real
            // threshold crossing silently unchecked 60% of the time.
            const levelAfterMilestone = calculateLevel(this.settings.gamificationTotalXP).level;
            const leveledUp = levelAfterMilestone > levelBeforeTick;
            const weekXP = sumRecentXP(this.settings.gamificationDailyXPLog, todayStr, 7);
            const newBestWeekXP = weekXP > this.settings.gamificationBestWeekXP;
            if (newBestWeekXP) this.settings.gamificationBestWeekXP = weekXP;
            const newlyUnlocked = this.applyNewBadgeUnlocks();

            // No streak/freeze/comeback candidates here — a mid-goal milestone
            // isn't a full "active day" event on its own; that's still decided
            // by whichever of task-completion or the writing goal is reached.
            this.flashMostExciting(
                [
                    { condition: newlyUnlocked.length > 0, flash: () => this.flashBadge(newlyUnlocked[newlyUnlocked.length - 1]) },
                    { condition: leveledUp, flash: () => this.flashLevelUp(levelAfterMilestone) },
                    { condition: newBestWeekXP, flash: () => this.flashPersonalBest({ streak: false, dayTasks: false, weekXP: true }) },
                ],
                milestoneBonus > 0 ? () => this.flash([{ icon: 'sparkles', text: `+${milestoneBonus} XP` }], 1400) : null
            );

            this.refreshViews();
            this.debouncedSave();
            return;
        }

        // Routine tick, nothing crossed a threshold. If the integration just
        // became available this render never happened yet (no DOM to patch),
        // so do one full render; otherwise patch just the writing meter.
        if (wasAvailable !== this.charStatsAvailable) {
            this.refreshViews();
        } else {
            this.updateTodayCharsLive(charsToday, goal);
        }
    }

    /**
     * Patch just the writing-goal meter's bar/count in every open
     * gamification view, instead of a full `refresh()` — see `refreshWordStats`.
     * Falls back to a full `refresh()` per-view when that view hasn't
     * rendered the meter yet (e.g. it was just opened, or the goal was just
     * turned on), since there's nothing to patch in that case.
     */
    private updateTodayCharsLive(current: number, goal: number) {
        for (const leaf of this.app.workspace.getLeavesOfType(VIEW_TYPE_GAMIFICATION)) {
            const view = leaf.view as unknown as {
                updateTodayChars?: (current: number, goal: number) => boolean;
                refresh?: () => void;
            };
            if (!view.updateTodayChars?.(current, goal)) {
                view.refresh?.();
            }
        }
    }

    /**
     * Grant the variable XP reward for hitting the daily writing goal,
     * mirroring `handleFileModify`'s reward flow. `levelBefore` must be the
     * level as it stood before *any* of this tick's XP was applied — the
     * caller (`refreshWordStats`) may have already folded in a same-tick
     * milestone bonus before calling this, and passing that already-mutated
     * level here would silently hide a level-up caused by the combination of
     * both rewards. Required rather than defaulted so every call site has to
     * consciously supply the right snapshot instead of an easy-to-miss
     * implicit ordering contract.
     */
    private grantCharGoalReward(todayStr: string, levelBefore: number) {
        this.settings.gamificationCharGoalLastAchievedDate = todayStr;

        const reward = rollReward(this.random);
        this.settings.gamificationTotalXP += reward.xp;
        this.logDailyXP(todayStr, todayStr, reward.xp);
        const levelAfter = calculateLevel(this.settings.gamificationTotalXP).level;
        const leveledUp = levelAfter > levelBefore;

        // Writing-goal XP feeds the same weekly-XP personal record task
        // completions do — otherwise a week driven entirely by hitting the
        // writing goal would never trigger a "BEST" moment.
        const weekXP = sumRecentXP(this.settings.gamificationDailyXPLog, todayStr, 7);
        const newBestWeekXP = weekXP > this.settings.gamificationBestWeekXP;
        if (newBestWeekXP) this.settings.gamificationBestWeekXP = weekXP;

        const { newlyUnlocked, newBestStreak, isComeback, freezeMilestoneBonus } = this.updateStreakAndBadges(todayStr, todayStr);

        // Same hidden-badge check as a task completion (Night Owl: something
        // completed between midnight and 5am) — hitting the writing goal is
        // just as valid a way to trigger it as checking off a task. Overdrive
        // (10+ tasks in a day) is inherently about the task count specifically,
        // not writing, but still worth checking here too: if the user already
        // completed 10+ tasks today before separately hitting the writing
        // goal, that should unlock it rather than waiting for an 11th task.
        const specialUnlocks = checkNewlySpecialUnlocks(
            { hour: new Date().getHours(), todayTaskCount: this.settings.gamificationDailyTaskLog[todayStr] ?? 0 },
            this.settings.gamificationUnlockedBadges
        );
        if (specialUnlocks.length > 0) {
            this.settings.gamificationUnlockedBadges.push(...specialUnlocks.map((b) => b.id));
        }
        const allNewBadges = [...newlyUnlocked, ...specialUnlocks];

        // Same "pick the most exciting thing that happened" priority chain as a task completion.
        this.flashMostExciting(
            [
                { condition: allNewBadges.length > 0, flash: () => this.flashBadge(allNewBadges[allNewBadges.length - 1]) },
                { condition: leveledUp, flash: () => this.flashLevelUp(levelAfter) },
                { condition: freezeMilestoneBonus > 0, flash: () => this.flash([{ icon: 'snowflake', text: `+${freezeMilestoneBonus} FREEZE` }], 2500) },
                { condition: newBestStreak || newBestWeekXP, flash: () => this.flashPersonalBest({ streak: newBestStreak, dayTasks: false, weekXP: newBestWeekXP }) },
                { condition: isComeback, flash: () => this.flash([{ icon: 'leaf', text: `Best ${this.settings.gamificationBestStreak}d kept · fresh start` }], 2500) },
            ],
            () => this.flash([{ icon: 'pen-line', text: 'GOAL' }, { icon: 'zap', text: `+${reward.xp} XP` }], 2200)
        );

        this.refreshViews();
        this.debouncedSave();
    }

    getSnapshot(): GamificationSnapshot {
        const { level, xpIntoLevel, xpForNextLevel } = calculateLevel(this.settings.gamificationTotalXP);
        const badges: BadgeSnapshot[] = ALL_BADGES.map((badge) => ({
            ...badge,
            unlocked: this.settings.gamificationUnlockedBadges.includes(badge.id),
        }));
        const todayStr = moment().format('YYYY-MM-DD');
        const stats = this.lastVaultStats;
        const lifetimeChars = stats ? lifetimeCharactersWritten(stats) : 0;
        const goal = this.settings.gamificationDailyCharGoal;
        return {
            enabled: this.settings.gamificationEnabled,
            level,
            levelTitle: titleForLevel(level),
            xpIntoLevel,
            xpForNextLevel,
            totalXP: this.settings.gamificationTotalXP,
            streak: this.settings.gamificationStreak,
            freezeTokensAvailable: this.settings.gamificationFreezeTokensAvailable,
            badges,
            todayProgress: this.todayProgress,
            totalTasksCompleted: this.settings.gamificationTotalTasksCompleted,
            startDate: this.settings.gamificationStartDate || null,
            weeklyXP: getWeeklyXPSeries(this.settings.gamificationDailyXPLog, todayStr, 7),
            monthlyXP: getWeeklyXPSeries(this.settings.gamificationDailyXPLog, todayStr, 30),
            nearestBadge: findNearestBadgeTarget(
                { level, streak: this.settings.gamificationStreak, chars: charsBadgeEligible(lifetimeChars, this.settings.gamificationCharsBadgeBaseline) },
                this.settings.gamificationUnlockedBadges
            ),
            freezeTokenLog: this.settings.gamificationFreezeTokenLog,
            bestStreak: this.settings.gamificationBestStreak,
            bestDayTasks: this.settings.gamificationBestDayTasks,
            bestWeekXP: this.settings.gamificationBestWeekXP,
            charStatsAvailable: this.charStatsAvailable,
            todayChars: stats && goal > 0 ? { current: charactersOn(stats, todayStr), goal } : null,
            weeklyChars: stats ? getWeeklyCharSeries(stats, todayStr, 7) : [],
            lifetimeCharsWritten: lifetimeChars,
            bestDayChars: stats ? bestDayCharacters(stats) : 0,
            bestWeekChars: stats ? bestWeekCharacters(stats) : 0,
        };
    }

    private refreshViews() {
        for (const leaf of this.app.workspace.getLeavesOfType(VIEW_TYPE_GAMIFICATION)) {
            const view = leaf.view as unknown as { refresh?: () => void };
            view.refresh?.();
        }
    }

    private renderStatusBar() {
        if (!this.statusBarItem) return;
        if (!this.settings.gamificationEnabled) {
            this.statusBarItem.empty();
            this.statusBarItem.style.display = 'none';
            return;
        }
        this.statusBarItem.style.display = '';
        const { level, xpIntoLevel, xpForNextLevel } = calculateLevel(this.settings.gamificationTotalXP);
        this.setStatusBarContent([
            { icon: 'zap', text: `Lv${level}` },
            { text: `${xpIntoLevel}/${xpForNextLevel}` },
            { icon: 'flame', text: `${this.settings.gamificationStreak}` },
            { icon: 'snowflake', text: `${this.settings.gamificationFreezeTokensAvailable}` },
        ]);
    }

    /** Render icon+text segments into the status bar, separated by a middle dot. */
    private setStatusBarContent(segments: StatusSegment[]) {
        const bar = this.statusBarItem;
        if (!bar) return;
        bar.empty();
        segments.forEach((segment, index) => {
            if (index > 0) bar.createSpan({ cls: 'crystal-gv-sep', text: '·' });
            if (segment.icon) {
                const iconEl = bar.createSpan({ cls: 'crystal-gv-status-icon' });
                setIcon(iconEl, segment.icon);
            }
            bar.createSpan({ text: segment.text });
        });
    }

    /**
     * Pick and fire the single most exciting flash from a candidate list, in
     * priority order — every XP-earning path (task completion, hitting the
     * writing goal, a mid-goal milestone) ends with "several things might
     * have happened at once; show only the best one", and previously each
     * path hand-rolled its own if/else priority chain, which had already
     * drifted out of sync once (a badge-unlock check silently missing from
     * one of the three). Callers pass only the candidates relevant to their
     * path — e.g. only an "active day" event (task completion, the writing
     * goal) carries streak/freeze/comeback candidates — so the *set* of
     * possible celebrations still differs per path; only the "pick the first
     * true one, else fall back" mechanism is shared. `fallback` may be `null`
     * when a path has no default flash to fall back to (e.g. a milestone
     * whose small bonus didn't happen to roll).
     */
    private flashMostExciting(candidates: Array<{ condition: boolean; flash: () => void }>, fallback: (() => void) | null) {
        const hit = candidates.find((c) => c.condition);
        if (hit) {
            hit.flash();
        } else {
            fallback?.();
        }
    }

    /**
     * Briefly replace the status bar content with the reward just earned, then
     * fall back to the normal Lv/XP/streak display. No popup — the payoff
     * lives entirely in the status bar so it never interrupts the editor.
     */
    private flashReward(reward: Reward) {
        const icon = reward.tier === 'rare' ? 'gem' : reward.tier === 'bonus' ? 'sparkles' : 'zap';
        this.flash([{ icon, text: `+${reward.xp} XP` }], 1500);
    }

    /** Same idea as `flashReward`, but for a newly unlocked badge (shown longer). */
    private flashBadge(badge: Badge) {
        this.flash([{ icon: 'award', text: 'NEW' }, { icon: badge.icon, text: badge.name }], 2500);
    }

    /** A level-up is the headline event of the whole XP system — it gets its
     * own moment instead of blending into a routine XP-reward flash. */
    private flashLevelUp(level: number) {
        this.flash([{ icon: 'trending-up', text: 'LEVEL UP' }, { icon: 'zap', text: `Lv${level}` }], 2500);
    }

    /** Celebrates beating a personal record — translates SNS-style "compare to others" into "compare to your past self". */
    private flashPersonalBest(broke: { streak: boolean; dayTasks: boolean; weekXP: boolean }) {
        const text = broke.streak ? `${this.settings.gamificationBestStreak}d streak`
            : broke.dayTasks ? `${this.settings.gamificationBestDayTasks}/day`
                : `${this.settings.gamificationBestWeekXP} XP/wk`;
        this.flash([{ icon: 'trophy', text: 'BEST' }, { text }], 2200);
    }

    private flash(segments: StatusSegment[], duration: number) {
        if (!this.statusBarItem || !this.settings.gamificationEnabled) return;

        // Lets hacker mode echo the moment with its own banner.
        this.app.workspace.trigger(GAMIFICATION_FLASH_EVENT, segments.map(seg => seg.text).join(' '), duration);
        this.setStatusBarContent(segments);
        this.statusBarItem.addClass('crystal-gamification-status--flash');

        if (this.flashTimeoutId !== null) {
            window.clearTimeout(this.flashTimeoutId);
        }
        this.flashTimeoutId = window.setTimeout(() => {
            this.statusBarItem?.removeClass('crystal-gamification-status--flash');
            this.flashTimeoutId = null;
            this.renderStatusBar();
        }, duration);
        this.plugin.registerInterval(this.flashTimeoutId);
    }

    /**
     * Persist settings after a short debounce window so rapid-fire checkbox
     * toggles (checking off several tasks at once) coalesce into a single
     * data.json write — and a single `updateSettings()` cascade across every
     * other service — instead of one per task.
     */
    private debouncedSave() {
        if (this.saveDebounceId !== null) {
            window.clearTimeout(this.saveDebounceId);
        }
        this.saveDebounceId = window.setTimeout(() => {
            this.saveDebounceId = null;
            this.plugin.saveSettings().catch((error) => {
                console.error('Crystal gamification: failed to save settings', error);
            });
        }, 400);
        this.plugin.registerInterval(this.saveDebounceId);
    }

    /**
     * Force out any pending debounced save immediately. Called on plugin
     * unload so a completion right before Obsidian closes/reloads doesn't
     * get lost in the debounce window.
     */
    flushPendingSave() {
        if (this.saveDebounceId === null) return;
        window.clearTimeout(this.saveDebounceId);
        this.saveDebounceId = null;
        this.plugin.saveSettings().catch((error) => {
            console.error('Crystal gamification: failed to save settings', error);
        });
    }
}

interface StatusSegment {
    icon?: string;
    text: string;
}

function tierRank(tier: RewardTier): number {
    return tier === 'rare' ? 2 : tier === 'bonus' ? 1 : 0;
}
